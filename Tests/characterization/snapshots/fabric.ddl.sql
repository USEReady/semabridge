CREATE OR REPLACE SEMANTIC VIEW "CHAR_DB"."CHAR_SCHEMA"."CHARACTERIZATION_MODEL_SEMANTIC"
TABLES (
  SALES AS "CHAR_DB"."CHAR_SCHEMA"."SALES",
  PRODUCT AS "CHAR_DB"."CHAR_SCHEMA"."PRODUCT" PRIMARY KEY ("PRODUCTKEY"),
  COL_DATE AS "CHAR_DB"."CHAR_SCHEMA"."DATE" PRIMARY KEY ("DATEKEY"),
  GEO AS "CHAR_DB"."CHAR_SCHEMA"."GEO" PRIMARY KEY ("GEOKEY")
)
RELATIONSHIPS (
  SALES_PRODUCTKEY_PRODUCT_PRODUCTKEY AS SALES ("PRODUCTKEY") REFERENCES PRODUCT ("PRODUCTKEY"),
  SALES_DATEKEY_DATE_DATEKEY AS SALES ("DATEKEY") REFERENCES COL_DATE ("DATEKEY"),
  SALES_GEOKEY_GEO_GEOKEY AS SALES ("GEOKEY") REFERENCES GEO ("GEOKEY")
)
FACTS (
  PRIVATE SALES."SALESKEY" AS SALES."SALESKEY",
  SALES."UNITS" AS SALES."UNITS",
  SALES."REVENUE" AS SALES."REVENUE",
  SALES."DISCOUNT" AS SALES."DISCOUNT"
)
DIMENSIONS (
  SALES."STATUS" AS SALES."STATUS",
  PRODUCT."PRODUCT" AS PRODUCT."PRODUCT",
  PRODUCT."MANUFACTURER" AS PRODUCT."MANUFACTURER",
  PRODUCT."SEGMENT" AS PRODUCT."SEGMENT",
  PRODUCT."CATEGORY" AS PRODUCT."CATEGORY",
  COL_DATE."COL_DATE" AS COL_DATE."COL_DATE" WITH SYNONYMS = ('Date'),
  COL_DATE."YEAR" AS COL_DATE."YEAR",
  COL_DATE."MONTH" AS COL_DATE."MONTH",
  GEO."REGION" AS GEO."REGION",
  GEO."STATE" AS GEO."STATE",
  PRIVATE SALES."PRODUCTKEY" AS SALES."PRODUCTKEY",
  PRIVATE SALES."DATEKEY" AS SALES."DATEKEY",
  PRIVATE SALES."GEOKEY" AS SALES."GEOKEY",
  PRIVATE PRODUCT."PRODUCTKEY" AS PRODUCT."PRODUCTKEY",
  PRIVATE COL_DATE."DATEKEY" AS COL_DATE."DATEKEY",
  PRIVATE GEO."GEOKEY" AS GEO."GEOKEY"
)
METRICS (
  SALES."TOTAL_UNITS" AS SUM(SALES.UNITS::FLOAT),
  SALES."TOTAL_REVENUE" AS SUM(SALES.REVENUE::FLOAT),
  SALES."NET_REVENUE" AS CASE WHEN (SUM(SALES.REVENUE::FLOAT)) IS NULL AND (SUM(SALES.DISCOUNT::FLOAT)) IS NULL THEN NULL ELSE COALESCE((SUM(SALES.REVENUE::FLOAT)), 0) - COALESCE(SUM(SALES.DISCOUNT::FLOAT), 0) END,
  SALES."MARGIN_PCT" AS (CASE WHEN (SUM(SALES.REVENUE::FLOAT)) IS NULL AND (SUM(SALES.DISCOUNT::FLOAT)) IS NULL THEN NULL ELSE COALESCE((SUM(SALES.REVENUE::FLOAT)), 0) - COALESCE(SUM(SALES.DISCOUNT::FLOAT), 0) END) / NULLIF((SUM(SALES.REVENUE::FLOAT)), 0),
  SALES."VANARSDEL_UNITS" AS SUM(CASE WHEN PRODUCT.MANUFACTURER = 'VanArsdel' THEN SALES.UNITS END::FLOAT) COMMENT = 'Note: DAX CALCULATE filters override existing filters on that column, while the SUM(CASE WHEN ...::FLOAT) translation doesn''t, so results differ when grouping by the filtered column.',
  SALES."VALID_UNITS" AS SUM(CASE WHEN NOT COALESCE((SALES.STATUS IN ('Cancelled', 'Returned')), FALSE) THEN SALES.UNITS ELSE NULL END::FLOAT) COMMENT = 'Note: DAX CALCULATE filters override existing filters on that column, while the SUM(CASE WHEN ...::FLOAT) translation doesn''t, so results differ when grouping by the filtered column.',
  SALES."UNITS_YTD" AS SUM(CASE WHEN COL_DATE.COL_DATE >= DATE_TRUNC('YEAR', CURRENT_DATE()) AND COL_DATE.COL_DATE <= CURRENT_DATE() THEN SALES.UNITS ELSE NULL END::FLOAT) COMMENT = 'Note: DAX CALCULATE filters override existing filters on that column, while the SUM(CASE WHEN ...::FLOAT) translation doesn''t, so results differ when grouping by the filtered column. Time-intelligence window is anchored to CURRENT_DATE() because no data-anchored period flag was available; DAX anchors to the last date in the filter context, so values differ when the data does not extend to today.',
  PRODUCT."PRODUCT_COUNT" AS COUNT(DISTINCT PRODUCT.PRODUCTKEY),
  SALES."SUM_OF_UNITS" AS SUM(SALES.UNITS::FLOAT),
  SALES."SUM_OF_REVENUE" AS SUM(SALES.REVENUE::FLOAT),
  SALES."SUM_OF_DISCOUNT" AS SUM(SALES.DISCOUNT::FLOAT)
);