CREATE OR REPLACE SEMANTIC VIEW "CHAR_DB"."CHAR_SCHEMA"."CHARACTERIZATION_SEMANTIC"
TABLES (
  SALES_FACT AS "CHAR_DB"."CHAR_SCHEMA"."SALES_FACT" COMMENT = 'Sales transactions',
  PRODUCT AS "CHAR_DB"."CHAR_SCHEMA"."PRODUCT" PRIMARY KEY ("PRODUCT_KEY") COMMENT = 'Products',
  DATE_DIM AS "CHAR_DB"."CHAR_SCHEMA"."DATE_DIM" COMMENT = 'Calendar',
  GEO AS "CHAR_DB"."CHAR_SCHEMA"."GEO" PRIMARY KEY ("GEO_KEY") COMMENT = 'Geography'
)
RELATIONSHIPS (
  SALES_FACT_PRODUCT_KEY_PRODUCT_PRODUCT_KEY AS SALES_FACT ("PRODUCT_KEY") REFERENCES PRODUCT ("PRODUCT_KEY"),
  SALES_FACT_GEO_KEY_GEO_GEO_KEY AS SALES_FACT ("GEO_KEY") REFERENCES GEO ("GEO_KEY")
)
FACTS (
  SALES_FACT."SALES_KEY" AS SALES_FACT."SALES_KEY",
  SALES_FACT."DATE_KEY" AS SALES_FACT."DATE_KEY",
  SALES_FACT."UNITS" AS SALES_FACT."UNITS",
  SALES_FACT."REVENUE" AS SALES_FACT."REVENUE",
  SALES_FACT."DISCOUNT" AS SALES_FACT."DISCOUNT"
)
DIMENSIONS (
  SALES_FACT."PRODUCT_KEY" AS SALES_FACT."PRODUCT_KEY",
  SALES_FACT."GEO_KEY" AS SALES_FACT."GEO_KEY",
  SALES_FACT."STATUS" AS SALES_FACT."STATUS",
  PRODUCT."PRODUCT_KEY" AS PRODUCT."PRODUCT_KEY",
  PRODUCT."PRODUCT" AS PRODUCT."PRODUCT",
  PRODUCT."MANUFACTURER" AS PRODUCT."MANUFACTURER",
  PRODUCT."SEGMENT" AS PRODUCT."SEGMENT",
  DATE_DIM."DATE_KEY" AS DATE_DIM."DATE_KEY",
  DATE_DIM."COL_DATE" AS DATE_DIM."COL_DATE" WITH SYNONYMS = ('DATE'),
  DATE_DIM."YEAR" AS DATE_DIM."YEAR",
  DATE_DIM."MONTH" AS DATE_DIM."MONTH",
  GEO."GEO_KEY" AS GEO."GEO_KEY",
  GEO."REGION" AS GEO."REGION",
  GEO."STATE" AS GEO."STATE"
)
METRICS (
  SALES_FACT."SUM_OF_SALES_KEY" AS SUM(SALES_FACT."SALES_KEY"::FLOAT),
  SALES_FACT."SUM_OF_UNITS" AS SUM(SALES_FACT."UNITS"::FLOAT),
  SALES_FACT."SUM_OF_REVENUE" AS SUM(SALES_FACT."REVENUE"::FLOAT),
  SALES_FACT."SUM_OF_DISCOUNT" AS SUM(SALES_FACT."DISCOUNT"::FLOAT)
);