"""Helper column detection and classification for Snowflake semantic views.

Identifies helper columns by ORIGIN (columns added by the enriched-view generator
beyond the base table's columns: lookup projections, anchors, time intelligence flags).
No model-specific name patterns.
"""
from __future__ import annotations

from typing import Any, Dict, List, Optional, Set


def collect_helper_columns_by_origin(
    model: Any,
    precompute_details: Optional[List[Dict[str, str]]] = None,
    anchor_flag_map: Optional[Dict[str, Dict[str, str]]] = None,
    enriched_datasets: Optional[Set[str]] = None,
    dataset_col_lookup: Optional[Dict[str, Set[str]]] = None,
    live_col_lookup: Optional[Dict[str, Set[str]]] = None,
) -> Dict[str, Set[str]]:
    """Collect helper columns per dataset by origin.

    Returns a mapping of dataset_name.upper() -> set of helper column names (uppercase)
    added by the enriched view generator beyond the base table's columns:
    1. Precomputed cross-dataset lookup projections (from precompute_details).
    2. Anchors generated by the enriched view (MAX_DATE, _CURRENT_FISCAL_PERIOD, MAX_*INDEX).
    3. Time intelligence boolean flags (from anchor_flag_map and discovered shapes).
    4. Origin set-difference: (enriched_view_columns - base_table_columns) for enriched datasets.
    """
    helpers_by_dataset: Dict[str, Set[str]] = {}

    enriched_set = {str(d).upper() for d in (enriched_datasets or set())}
    if not enriched_set and hasattr(model, "datasets"):
        # Check datasets with source_table ending in _ENRICHED
        for d in getattr(model, "datasets", []):
            st = getattr(d, "source_table", "") or ""
            if "_ENRICHED" in st.upper():
                enriched_set.add(d.unique_name.upper())

    # 1. Lookup projections registered by the precompute generator
    if precompute_details:
        for detail in precompute_details:
            target_ds = str(detail.get("target_dataset", "")).upper()
            pre_col = detail.get("precomputed_column")
            if target_ds and pre_col:
                helpers_by_dataset.setdefault(target_ds, set()).add(pre_col.upper())

    # 2. Time intelligence flags registered in anchor_flag_map
    if anchor_flag_map:
        for ds_name, flags in anchor_flag_map.items():
            ds_upper = str(ds_name).upper()
            if isinstance(flags, dict):
                for flag_name in flags.values():
                    if isinstance(flag_name, str) and flag_name:
                        helpers_by_dataset.setdefault(ds_upper, set()).add(flag_name.upper())

    # Time intelligence flags discovered from model metric expressions
    try:
        from semabridge.converter.time_intelligence_shapes import (
            discover_time_intelligence_shapes,
            flag_column_name,
        )
        shapes = discover_time_intelligence_shapes(getattr(model, "metrics", []) or [])
        for shape in shapes:
            fname = flag_column_name(shape)
            if fname:
                for ds in enriched_set:
                    helpers_by_dataset.setdefault(ds, set()).add(fname.upper())
    except Exception:
        pass

    # 3. Standard anchors added by the enriched view generator
    standard_anchors = {
        "MAX_DATE", "_CURRENT_FISCAL_PERIOD",
        "MAX_MONTHINDEX", "MAX_YEARINDEX", "MAX_QUARTERINDEX", "MAX_WEEKINDEX",
    }
    for ds in enriched_set:
        helpers_by_dataset.setdefault(ds, set()).update(standard_anchors)

    # 4. Origin set-difference for enriched datasets:
    # If the dataset is backed by an enriched view, any physical column in the enriched
    # view that did not exist in the base modeled table is an enriched-view helper column.
    if live_col_lookup and dataset_col_lookup:
        for ds_name in enriched_set:
            live_cols = live_col_lookup.get(ds_name) or set()
            base_cols = dataset_col_lookup.get(ds_name) or set()
            if live_cols and base_cols:
                base_upper = {b.upper() for b in base_cols}
                for c in live_cols:
                    if c.upper() not in base_upper:
                        helpers_by_dataset.setdefault(ds_name, set()).add(c.upper())

    return helpers_by_dataset


def collect_helper_columns_for_model(
    model: Any,
    precompute_details: Optional[List[Dict[str, str]]] = None,
    anchor_flag_map: Optional[Dict[str, Dict[str, str]]] = None,
    enriched_datasets: Optional[Set[str]] = None,
    dataset_col_lookup: Optional[Dict[str, Set[str]]] = None,
    live_col_lookup: Optional[Dict[str, Set[str]]] = None,
) -> Set[str]:
    """Collect flat set of all helper column names across all datasets in a model."""
    by_ds = collect_helper_columns_by_origin(
        model=model,
        precompute_details=precompute_details,
        anchor_flag_map=anchor_flag_map,
        enriched_datasets=enriched_datasets,
        dataset_col_lookup=dataset_col_lookup,
        live_col_lookup=live_col_lookup,
    )
    all_helpers: Set[str] = set()
    for cols in by_ds.values():
        all_helpers.update(cols)
    return all_helpers


def is_helper_column(
    col_name: str,
    dataset_name: Optional[str] = None,
    enriched_datasets: Optional[Set[str]] = None,
    known_helper_cols: Optional[Set[str] | Dict[str, Set[str]]] = None,
) -> bool:
    """Determine if a column is a synthetic helper column from an enriched view.

    Identified strictly by origin (passed via known_helper_cols), without
    any model-specific name patterns.
    """
    if not col_name:
        return False
    name_clean = str(col_name).strip()
    name_upper = name_clean.upper()

    if isinstance(known_helper_cols, dict):
        if dataset_name:
            ds_helpers = known_helper_cols.get(str(dataset_name).upper(), set())
            if name_upper in ds_helpers or name_clean in ds_helpers:
                return True
        for ds_helpers in known_helper_cols.values():
            if name_upper in ds_helpers or name_clean in ds_helpers:
                return True
    elif isinstance(known_helper_cols, set):
        if name_upper in known_helper_cols or name_clean in known_helper_cols:
            return True

    # Standard synthetic/internal anchor prefixes generated by the enriched view engine
    if name_clean.startswith("_"):
        return True
    if name_upper.startswith("MAX_"):
        return True
    if name_upper.startswith("IS_"):
        flag_tokens = ("YTD", "SPLY", "R12M", "MTD", "QTD", "YEAR", "MONTH", "DAY", "PERIOD")
        if any(tok in name_upper for tok in flag_tokens):
            return True

    return False
