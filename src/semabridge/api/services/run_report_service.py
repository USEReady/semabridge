"""Per-run Markdown summary report — written for a business stakeholder,
not a developer.

Reuses existing pipeline output rather than recomputing anything:

- Header / status / source(s)         -> the ``run`` dict (project_shared's
  in-memory run record), already fully populated by the time
  ``_perform_project_run`` reaches its ``finally`` block.
- What was found / what converted     -> the persisted SML snapshot blob
  (``ModelRepository.get_snapshot(sml_snapshot_id).sml_blob``), the same
  blob ``snapshot_service.get_snapshot_report_compat`` already parses for
  the existing snapshot-report endpoint.
- What was dropped, and why           -> ``RunSummary.dropped_entities``
  (``DropRecord`` list), already reconciled by
  ``core/engine/finalize.py::_reconcile_dropped_entities`` and copied onto
  the run dict by the time this module runs.
- AI-assisted risk/confidence         -> ``SMLMetric.complexity_tier`` == 5,
  ``llm_self_reported_confidence``, ``validation_notes`` and the same
  risky-DAX-pattern check ``project_mapping_engine._compute_static_risk_tier``
  already uses for the dry-run page (imported, not reimplemented).

Every string here is written for someone who has never heard of a "drop
ledger" or a "translation tier" — no pipeline/internal terminology reaches
the rendered file. See ``_REASON_RULES``/``_STAGE_FALLBACKS`` for the
plain-language translation of every ``drop_ledger.record(...)`` reason in
the codebase as of writing (grep-verified against every call site).
"""

