def _load_snapshot_data(sml_snapshot_id: Optional[str]) -> Optional[Dict[str, Any]]:
    """Load a persisted SML snapshot's datasets/metrics/relationships.

    One extra DB read, exactly the pattern
    snapshot_service.get_snapshot_report_compat already uses to recompute
    total_models/total_columns for the existing snapshot-report endpoint --
    the live SMLModel object itself is discarded once ExecutionEngine.execute()
    returns, so this is the only place per-metric complexity_tier/
    llm_self_reported_confidence/advisory data still exists after the run.
    """
    if not sml_snapshot_id:
        return None
    try:
        from semabridge.repository.model_repository import ModelRepository

        snap = ModelRepository().get_snapshot(str(sml_snapshot_id))
    except Exception:
        logger.debug(
            "Run report: could not load snapshot %s", sml_snapshot_id, exc_info=True
        )
        return None
    if not snap or not isinstance(snap.sml_blob, dict):
        return None
    blob = snap.sml_blob
    datasets = [d for d in (blob.get("datasets") or []) if isinstance(d, dict)]
    return {
        "dataset_count": len(datasets),
        "column_count": sum(len(d.get("columns") or []) for d in datasets),
        "relationship_count": len(blob.get("relationships") or []),
        "metrics": [m for m in (blob.get("metrics") or []) if isinstance(m, dict)],
    }


def _classify_metrics(sml_metrics: List[Dict[str, Any]]) -> Dict[str, List[Dict[str, Any]]]:
    """Split a snapshot's metrics into Standard / AI-assisted / Needs
    Review, reusing the same risky-DAX-pattern check the dry-run page's
    three-tier risk label already uses (project_mapping_engine.py) rather
    than reimplementing it.

    "known risky pattern" in _compute_static_risk_tier is structurally
    reachable ONLY inside its `if is_tier5:` branch -- so that signal is
    folded into the AI-assisted entries below, not a separate section.

    Needs Review is checked FIRST, independent of tier: a metric carrying
    an advisory_category in REVIEW_REQUIRED_ADVISORY_CATEGORIES (e.g. an
    unshifted time-intelligence fallback, or a decomposed disconnected-
    selector branch) goes there regardless of whether it's tier 1-4 or
    tier 5 -- the same signal dry-run's "Needs Attention" chip already
    keys off, now surfaced post-run too, instead of blending into Standard/
    AI-assisted with just a generic advisory message tacked on.
    """
    from semabridge.api.services.project_mapping_engine import (
        _has_known_risky_dax_pattern,
        REVIEW_REQUIRED_ADVISORY_CATEGORIES,
    )

    advisory_messages = _advisory_category_messages()
    standard: List[Dict[str, Any]] = []
    ai_assisted: List[Dict[str, Any]] = []
    needs_review: List[Dict[str, Any]] = []

    for metric in sml_metrics:
        if not metric.get("sync_enabled", True):
            continue  # not successfully converted -- appears in the drop ledger instead
        name = metric.get("unique_name") or metric.get("label") or "Unnamed calculation"
        tier = metric.get("complexity_tier") or 1
        categories = metric.get("advisory_categories") or []
        notes_present = bool(metric.get("advisory_notes"))
        advisory_msgs = [advisory_messages.get(cat, _ADVISORY_FALLBACK_MESSAGE) for cat in categories]
        if not advisory_msgs and notes_present:
            advisory_msgs = [_ADVISORY_FALLBACK_MESSAGE]

        if set(categories) & REVIEW_REQUIRED_ADVISORY_CATEGORIES:
            needs_review.append({"name": name, "advisory_msgs": advisory_msgs})
        elif tier == 5:
            is_risky = bool(metric.get("validation_notes")) or _has_known_risky_dax_pattern(
                str(metric.get("expression") or "")
            )
            ai_assisted.append(
                {
                    "name": name,
                    "confidence": metric.get("llm_self_reported_confidence"),
                    "risky": is_risky,
                    "advisory_msgs": advisory_msgs,
                }
            )
        else:
            standard.append({"name": name, "advisory_msgs": advisory_msgs})

    return {"standard": standard, "ai_assisted": ai_assisted, "needs_review": needs_review}


# ---------------------------------------------------------------------------
# Source description (source-type-agnostic: local PBIX single/multi-file,
# Fabric)
# ---------------------------------------------------------------------------

def _parse_project_cfg(project_cfg: str) -> Dict[str, Any]:
    # Deliberately re-implemented here (not imported from run_service.py's
    # _compat_parse_project_cfg_dict) to avoid a circular import --
    # run_service.py imports write_run_report from this module.
    import yaml

    try:
        parsed = yaml.safe_load(project_cfg or "") or {}
        return parsed if isinstance(parsed, dict) else {}
    except Exception:
        return {}


def _describe_source(project_cfg: str, run: Dict[str, Any]) -> Tuple[str, List[str]]:
    """Returns (source kind label, [one description per source file/dataset]).

    Reads the same source config every source type already funnels through
    (execution_config.SourceConfig / sync_execution_service._build_sync_jobs)
    -- nothing here branches on anything other than `type`.
    """
    parsed = _parse_project_cfg(project_cfg)
    source_cfg = parsed.get("source") if isinstance(parsed.get("source"), dict) else {}
    source_type = str(run.get("source_type") or source_cfg.get("type") or "").lower()

    if source_type == "pbix":
        pbix_path = source_cfg.get("pbix_path") or source_cfg.get("source_path") or source_cfg.get("file_path")
        if pbix_path:
            return "Local file", [Path(str(pbix_path)).name]
        models = source_cfg.get("models") or []
        if models:
            return "Local files", [Path(str(m)).name for m in models]
        labels = [
            str(r.get("model")) for r in (run.get("results") or [])
            if isinstance(r, dict) and r.get("model")
        ]
        return "Local file(s)", labels or ["(file name unavailable)"]

    if source_type == "fabric":
        dataset = source_cfg.get("dataset_id") or "(unknown dataset)"
        workspace = source_cfg.get("workspace_id")
        label = f"Fabric dataset {dataset}"
        if workspace:
            label += f" (workspace {workspace})"
        return "Microsoft Fabric", [label]

    if source_type == "snowflake":
        models = source_cfg.get("models") or []
        return "Snowflake", [str(m) for m in models] or ["(view name unavailable)"]

    return source_type.title() or "Unknown source", []


