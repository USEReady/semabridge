# Source description (source-type-agnostic: local PBIX single/multi-file,
# Fabric)
# ---------------------------------------------------------------------------

def _parse_project_cfg(project_cfg: str) -> Dict[str, Any]:
    # Deliberately re-implemented here (not imported from run_service.py's
    # _compat_parse_project_cfg_dict) to avoid a circular import --
    # run_service.py imports write_run_report from this module.
    import yaml

    try:
        parsed = yaml.safe_load(project_cfg or "") or {}
        return parsed if isinstance(parsed, dict) else {}
    except Exception:
        return {}


def _describe_source(project_cfg: str, run: Dict[str, Any]) -> Tuple[str, List[str]]:
    """Returns (source kind label, [one description per source file/dataset]).

    Reads the same source config every source type already funnels through
    (execution_config.SourceConfig / sync_execution_service._build_sync_jobs)
    -- nothing here branches on anything other than `type`.
    """
    parsed = _parse_project_cfg(project_cfg)
    source_cfg = parsed.get("source") if isinstance(parsed.get("source"), dict) else {}
    source_type = str(run.get("source_type") or source_cfg.get("type") or "").lower()

    if source_type == "pbix":
        pbix_path = source_cfg.get("pbix_path") or source_cfg.get("source_path") or source_cfg.get("file_path")
        if pbix_path:
            return "Local file", [Path(str(pbix_path)).name]
        models = source_cfg.get("models") or []
        if models:
            return "Local files", [Path(str(m)).name for m in models]
        labels = [
            str(r.get("model")) for r in (run.get("results") or [])
            if isinstance(r, dict) and r.get("model")
        ]
        return "Local file(s)", labels or ["(file name unavailable)"]

    if source_type == "fabric":
        dataset = source_cfg.get("dataset_id") or "(unknown dataset)"
        workspace = source_cfg.get("workspace_id")
        label = f"Fabric dataset {dataset}"
        if workspace:
            label += f" (workspace {workspace})"
        return "Microsoft Fabric", [label]

    if source_type == "snowflake":
        models = source_cfg.get("models") or []
        return "Snowflake", [str(m) for m in models] or ["(view name unavailable)"]

    return source_type.title() or "Unknown source", []


def _describe_source_for_result(
    result: Dict[str, Any], project_cfg: str, run: Dict[str, Any]
) -> Tuple[str, List[str]]:
    """Same (source kind, [files]) shape as _describe_source(), but scoped to
    ONE model's own result -- used when rendering a per-model report for a
    multi-PBIX batch, so its "Source:" line names only that file instead of
    every file in the batch (see generate_per_model_reports()).

    Falls back to the whole-run description when the result carries no
    pbix_path of its own (single-model runs, and non-PBIX sources, which
    don't fan out into multiple files today).
    """
    pbix_path = result.get("pbix_path")
    if pbix_path:
        return "Local file", [Path(str(pbix_path)).name]
    return _describe_source(project_cfg, run)


