def _load_snapshot_data(sml_snapshot_id: Optional[str]) -> Optional[Dict[str, Any]]:
    """Load a persisted SML snapshot's datasets/metrics/relationships.

    One extra DB read, exactly the pattern
    snapshot_service.get_snapshot_report_compat already uses to recompute
    total_models/total_columns for the existing snapshot-report endpoint --
    the live SMLModel object itself is discarded once ExecutionEngine.execute()
    returns, so this is the only place per-metric complexity_tier/
    llm_self_reported_confidence/advisory data still exists after the run.
    """
    if not sml_snapshot_id:
        return None
    try:
        from semabridge.repository.model_repository import ModelRepository

        snap = ModelRepository().get_snapshot(str(sml_snapshot_id))
    except Exception:
        logger.debug(
            "Run report: could not load snapshot %s", sml_snapshot_id, exc_info=True
        )
        return None
    if not snap or not isinstance(snap.sml_blob, dict):
        return None
    blob = snap.sml_blob
    datasets = [d for d in (blob.get("datasets") or []) if isinstance(d, dict)]
    return {
        "dataset_count": len(datasets),
        "column_count": sum(len(d.get("columns") or []) for d in datasets),
        "relationship_count": len(blob.get("relationships") or []),
        "metrics": [m for m in (blob.get("metrics") or []) if isinstance(m, dict)],
    }


def _classify_metrics(sml_metrics: List[Dict[str, Any]]) -> Dict[str, List[Dict[str, Any]]]:
    """Split a snapshot's metrics into Standard / Standard-with-a-flag /
    AI-assisted, reusing the same risky-DAX-pattern check the dry-run page's
    three-tier risk label already uses (project_mapping_engine.py) rather
    than reimplementing it.

    "known risky pattern" in _compute_static_risk_tier is structurally
    reachable ONLY inside its `if is_tier5:` branch -- so that signal is
    folded into the AI-assisted entries below, not a separate section.
    advisory_notes/advisory_categories (osi_to_sml.py's unreachable-
    dimension check), however, run over every metric regardless of tier --
    so a Standard-conversion metric can carry a real flag too, and does get
    one here.
    """
    from semabridge.api.services.project_mapping_engine import _has_known_risky_dax_pattern

    advisory_messages = _advisory_category_messages()
    standard: List[Dict[str, Any]] = []
    ai_assisted: List[Dict[str, Any]] = []

    for metric in sml_metrics:
        if not metric.get("sync_enabled", True):
            continue  # not successfully converted -- appears in the drop ledger instead
        name = metric.get("unique_name") or metric.get("label") or "Unnamed calculation"
        tier = metric.get("complexity_tier") or 1
        categories = metric.get("advisory_categories") or []
        notes_present = bool(metric.get("advisory_notes"))
        advisory_msgs = [advisory_messages.get(cat, _ADVISORY_FALLBACK_MESSAGE) for cat in categories]
        if not advisory_msgs and notes_present:
            advisory_msgs = [_ADVISORY_FALLBACK_MESSAGE]

        if tier == 5:
            is_risky = bool(metric.get("validation_notes")) or _has_known_risky_dax_pattern(
                str(metric.get("expression") or "")
            )
            ai_assisted.append(
                {
                    "name": name,
                    "confidence": metric.get("llm_self_reported_confidence"),
                    "risky": is_risky,
                    "advisory_msgs": advisory_msgs,
                }
            )
        else:
            standard.append({"name": name, "advisory_msgs": advisory_msgs})

    return {"standard": standard, "ai_assisted": ai_assisted}


