# advisory_categories is a stable code, not free text -- REAL_DEPLOY_ONLY_
# ADVISORY_CATEGORIES in project_mapping_engine.py is a one-entry set today
# (ADVISORY_CATEGORY_UNREACHABLE_DIMENSION), so this dict has one real entry
# plus a generic fallback for whatever category is added next.
_ADVISORY_FALLBACK_MESSAGE = (
    "This calculation was flagged with a structural note during "
    "conversion. We recommend double-checking this number."
)


def _advisory_category_messages() -> Dict[str, str]:
    from semabridge.converter.dax_ast_parser import ADVISORY_CATEGORY_UNREACHABLE_DIMENSION

    return {
        ADVISORY_CATEGORY_UNREACHABLE_DIMENSION: (
            "This calculation references data from a different part of "
            "your source model that isn't connected to it. It converted, "
            "but we recommend double-checking this number."
        ),
    }


def humanize_drop_reason(record: Dict[str, Any]) -> str:
    """Translate one DropRecord dict's `reason` into a plain sentence."""
    reason = str(record.get("reason") or "")
    stage = str(record.get("stage") or "")
    lowered = reason.lower()
    for needle, plain in _REASON_RULES:
        if needle in lowered:
            return plain
    return _STAGE_FALLBACKS.get(
        stage, "This item could not be included in the converted model."
    )


def stage_group_label(stage: str, target_label: str = "the destination") -> str:
    template = _STAGE_GROUP_LABELS.get(stage, "During conversion")
    return template.format(target=target_label) if "{target}" in template else template


