METRICS (
  EMPLOYEE."EMPLOYEES" NON ADDITIVE BY ( COL_DATE."PERIOD_NUMBER" ASC ) AS COUNT(EMPLOYEE.EMPLID),
  EMPLOYEE."SEPARATIONS" AS COUNT(CASE WHEN (EMPLOYEE.TERMDATE IS NOT NULL) THEN EMPLOYEE.EMPLID END),
  EMPLOYEE."ACTIVES" NON ADDITIVE BY ( COL_DATE."PERIOD_NUMBER" ASC ) AS COUNT(CASE WHEN (EMPLOYEE.TERMDATE IS NULL) THEN EMPLOYEE.EMPLID ELSE NULL END),
  EMPLOYEE."NEW_HIRES" AS SUM(EMPLOYEE.ISNEWHIRE::FLOAT),
  EMPLOYEE."AVG_TENURE_DAYS" AS AVG(EMPLOYEE.TENUREDAYS),
  EMPLOYEE."AVG_TENURE_MONTHS" AS ROUND((AVG(EMPLOYEE.TENUREDAYS)) / NULLIF(30, 0), 1) - 1,
  EMPLOYEE."AVG_AGE" AS ROUND(AVG(EMPLOYEE.AGE::FLOAT), 0),
  EMPLOYEE."NEW_HIRES_SPLY" AS SUM(CASE WHEN EMPLOYEE.IS_SPLY_YEAR THEN EMPLOYEE.ISNEWHIRE ELSE NULL END::FLOAT),
  EMPLOYEE."ACTIVES_SPLY" AS CAST(NULL AS DOUBLE) COMMENT = 'not applicable: depends on non-additive metric [ACTIVES]',
  EMPLOYEE."SEPS_SPLY" AS COUNT(CASE WHEN EMPLOYEE.IS_SPLY_YEAR THEN CASE WHEN (EMPLOYEE.TERMDATE IS NOT NULL) THEN EMPLOYEE.EMPLID END ELSE NULL END),
  EMPLOYEE."EMPLOYEES_SPLY" AS CAST(NULL AS DOUBLE) COMMENT = 'not applicable: depends on non-additive metric',
  EMPLOYEE."SEPS_YOY_VAR" AS (COUNT(CASE WHEN (EMPLOYEE.TERMDATE IS NOT NULL) THEN EMPLOYEE.EMPLID END)) - (COUNT(CASE WHEN EMPLOYEE.IS_SPLY_YEAR THEN CASE WHEN (EMPLOYEE.TERMDATE IS NOT NULL) THEN EMPLOYEE.EMPLID END ELSE NULL END)),
  EMPLOYEE."ACTIVES_YOY_VAR" AS CAST(NULL AS DOUBLE) COMMENT = 'not applicable: depends on non-additive metric [ACTIVES]',
  EMPLOYEE."NEW_HIRES_YOY_VAR" AS (SUM(EMPLOYEE.ISNEWHIRE::FLOAT)) - (SUM(CASE WHEN EMPLOYEE.IS_SPLY_YEAR THEN EMPLOYEE.ISNEWHIRE ELSE NULL END::FLOAT)),
  EMPLOYEE."SEPS_YOY_PCT_CHANGE" AS ((COUNT(CASE WHEN (EMPLOYEE.TERMDATE IS NOT NULL) THEN EMPLOYEE.EMPLID END)) - (COUNT(CASE WHEN EMPLOYEE.IS_SPLY_YEAR THEN CASE WHEN (EMPLOYEE.TERMDATE IS NOT NULL) THEN EMPLOYEE.EMPLID END ELSE NULL END))) / NULLIF(COUNT(CASE WHEN EMPLOYEE.IS_SPLY_YEAR THEN CASE WHEN (EMPLOYEE.TERMDATE IS NOT NULL) THEN EMPLOYEE.EMPLID END ELSE NULL END), 0),
  EMPLOYEE."ACTIVES_YOY_PCT_CHANGE" AS CAST(NULL AS DOUBLE) COMMENT = 'not applicable: depends on non-additive metric [ACTIVES_SPLY]',
  EMPLOYEE."NEW_HIRES_YOY_PCT_CHANGE" AS ((SUM(EMPLOYEE.ISNEWHIRE::FLOAT)) - (SUM(CASE WHEN EMPLOYEE.IS_SPLY_YEAR THEN EMPLOYEE.ISNEWHIRE ELSE NULL END::FLOAT))) / NULLIF(SUM(CASE WHEN EMPLOYEE.IS_SPLY_YEAR THEN EMPLOYEE.ISNEWHIRE ELSE NULL END::FLOAT), 0),
  EMPLOYEE."BAD_HIRES_SPLY" AS SUM(CASE WHEN EMPLOYEE.IS_SPLY_YEAR THEN EMPLOYEE.BADHIRES ELSE NULL END::FLOAT),
  EMPLOYEE."BAD_HIRES_YOY_VAR" AS (SUM(EMPLOYEE.BADHIRES::FLOAT)) - (SUM(CASE WHEN EMPLOYEE.IS_SPLY_YEAR THEN EMPLOYEE.BADHIRES ELSE NULL END::FLOAT)),
  EMPLOYEE."BAD_HIRES_YOY_PCT_CHANGE" AS ((SUM(EMPLOYEE.BADHIRES::FLOAT)) - (SUM(CASE WHEN EMPLOYEE.IS_SPLY_YEAR THEN EMPLOYEE.BADHIRES ELSE NULL END::FLOAT))) / NULLIF(SUM(CASE WHEN EMPLOYEE.IS_SPLY_YEAR THEN EMPLOYEE.BADHIRES ELSE NULL END::FLOAT), 0),
  EMPLOYEE."SEP_PCT_OF_ACTIVE" AS CAST(NULL AS DOUBLE) COMMENT = 'not applicable: depends on non-additive metric [ACTIVES]',
  EMPLOYEE."SEP_PCT_OF_SMLY_ACTIVES" AS CAST(NULL AS DOUBLE) COMMENT = 'not applicable: depends on non-additive metric [ACTIVES_SPLY]',
  EMPLOYEE."BAD_HIRES_PCT_OF_ACTIVES" AS CAST(NULL AS DOUBLE) COMMENT = 'not applicable: depends on non-additive metric [ACTIVES]',
  EMPLOYEE."BAD_HIRES_PCT_OF_ACTIVE_SPLY" AS CAST(NULL AS DOUBLE) COMMENT = 'not applicable: depends on non-additive metric [ACTIVES_SPLY]',
  EMPLOYEE."BAD_HIRES" AS SUM(EMPLOYEE.BADHIRES::FLOAT)
);