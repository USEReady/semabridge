  BUSINESS_UNIT AS "SEMABRIDGE"."TESTING_SEMABRIDGE_CHECK"."EHH_BUSINESS_UNIT" PRIMARY KEY ("BU"),
  COL_DATE AS "SEMABRIDGE"."TESTING_SEMABRIDGE_CHECK"."COL_DATE" PRIMARY KEY ("DATE"),
