  BUSINESS_UNIT."REGION_WITH_ORDER" AS BUSINESS_UNIT."REGION_WITH_ORDER",
  COL_DATE."MONTH_INCREMENT_NUMBER" AS COL_DATE."MONTHINCREMENTNUMBER",
  EMPLOYEE."EMPLOYEE_DATE" AS EMPLOYEE."DATE",
  EMPLOYEE."EMPLID" AS EMPLOYEE."EMPLID",
  EMPLOYEE."EMPLOYEE_GENDER" AS EMPLOYEE."GENDER",
  EMPLOYEE."AGE" AS EMPLOYEE."AGE",
  EMPLOYEE."ETHNICGROUP" AS EMPLOYEE."ETHNICGROUP",
  EMPLOYEE."FP" AS EMPLOYEE."FP",
