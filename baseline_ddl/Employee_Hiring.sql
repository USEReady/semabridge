  EMPLOYEE_BU_BUSINESS_UNIT_BU AS EMPLOYEE ("BU") REFERENCES BUSINESS_UNIT ("BU"),
  EMPLOYEE_AGEGROUPID_AGE_AGE_GROUP_ID AS EMPLOYEE ("AGEGROUPID") REFERENCES AGE ("AGEGROUPID"),
  EMPLOYEE_TERMREASON_SEPARATION_REASON_SEPARATION_REASON_ID AS EMPLOYEE ("TERMREASON") REFERENCES SEPARATION_REASON ("SEPARATION_REASON_ID")
