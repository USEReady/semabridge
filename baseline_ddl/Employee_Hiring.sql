  EMPLOYEE_FP_EMPLOYEE_TYPE_EMPLOYEE_TYPE_ID AS EMPLOYEE ("FP") REFERENCES EMPLOYEE_TYPE ("EMPLOYEE_TYPE_ID"),
  EMPLOYEE_ETHNICGROUP_ETHNICITY_ETHNICITY_GROUP_ID AS EMPLOYEE ("ETHNICGROUP") REFERENCES ETHNICITY ("ETHNICITY_GROUP_ID"),
  EMPLOYEE_GENDER_GENDER_GENDER_ID AS EMPLOYEE ("GENDER") REFERENCES GENDER ("ID"),
