CREATE OR REPLACE SEMANTIC VIEW SEMABRIDGE.SALES_AND_RETURNS.SALES_RETURNS_SEMANTIC
    TABLES (
        CUSTOMER AS SEMABRIDGE.SALES_AND_RETURNS.CUSTOMER_ENRICHED,
        SEMABRIDGE.SALES_AND_RETURNS.SALES,
        PRODUCT AS SEMABRIDGE.SALES_AND_RETURNS.PRODUCT PRIMARY KEY (PRODUCTID),
        ASSOCIATED_PRODUCT AS SEMABRIDGE.SALES_AND_RETURNS.ASSOCIATED_PRODUCT PRIMARY KEY (PRODUCTID)
    )
    RELATIONSHIPS (
        CUSTOMER_ID_SALES_ID AS CUSTOMER(ID) REFERENCES SALES(ID),
        PRODUCT_AP AS PRODUCT(PRODUCT) REFERENCES ASSOCIATED_PRODUCT(PRODUCT),
        CUSTOMER_PRODUCT_AP AS CUSTOMER(PRODUCT) REFERENCES ASSOCIATED_PRODUCT(PRODUCT)
    );
